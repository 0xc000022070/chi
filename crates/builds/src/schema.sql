CREATE TABLE IF NOT EXISTS builds (
  id INTEGER PRIMARY KEY,
  org_id INTEGER NOT NULL,
  repo_id INTEGER NOT NULL,
  version TEXT NOT NULL,
  commit_sha TEXT NOT NULL,
  branch TEXT NOT NULL,
  tag TEXT NOT NULL,
  builder TEXT NOT NULL,
  status TEXT NOT NULL,
  started_at INTEGER NOT NULL,
  finished_at INTEGER
);
CREATE INDEX IF NOT EXISTS builds_listing ON builds (org_id, id);
CREATE TABLE IF NOT EXISTS artifacts (
  id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL REFERENCES builds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  size INTEGER NOT NULL,
  sha256 TEXT NOT NULL,
  UNIQUE (build_id, name)
);
CREATE TABLE IF NOT EXISTS deliveries (
  id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL REFERENCES builds(id) ON DELETE CASCADE,
  target TEXT NOT NULL,
  ok INTEGER NOT NULL,
  output TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS downloads (
  id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL REFERENCES builds(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  who TEXT NOT NULL,
  ip TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS contexts (
  build_id INTEGER PRIMARY KEY REFERENCES builds(id) ON DELETE CASCADE,
  base TEXT NOT NULL,
  commits TEXT NOT NULL,
  diffstat TEXT NOT NULL,
  diff TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS notes (
  build_id INTEGER PRIMARY KEY REFERENCES builds(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS links (
  id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL REFERENCES builds(id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  url TEXT NOT NULL,
  UNIQUE (build_id, url)
);
CREATE TABLE IF NOT EXISTS runs (
  id INTEGER PRIMARY KEY,
  build_id INTEGER NOT NULL REFERENCES builds(id) ON DELETE CASCADE,
  flake TEXT NOT NULL,
  status TEXT NOT NULL,
  error TEXT NOT NULL DEFAULT '',
  started_at INTEGER NOT NULL,
  finished_at INTEGER
);
CREATE INDEX IF NOT EXISTS runs_by_build ON runs (build_id, id);
CREATE TABLE IF NOT EXISTS steps (
  id INTEGER PRIMARY KEY,
  run_id INTEGER NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  status TEXT NOT NULL,
  output TEXT NOT NULL DEFAULT '',
  started_at INTEGER,
  finished_at INTEGER
);
CREATE TABLE IF NOT EXISTS updates (
  id INTEGER PRIMARY KEY,
  repo_id INTEGER NOT NULL,
  org TEXT NOT NULL,
  repo TEXT NOT NULL,
  channel TEXT NOT NULL,
  platform TEXT NOT NULL,
  runtime TEXT NOT NULL,
  commit_sha TEXT NOT NULL,
  manifest TEXT NOT NULL,
  at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS updates_newest ON updates (org, repo, channel, platform, runtime, id);
CREATE TABLE IF NOT EXISTS update_assets (
  sha256 TEXT PRIMARY KEY,
  size INTEGER NOT NULL,
  at INTEGER NOT NULL,
  stored INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS update_files (
  update_id INTEGER NOT NULL REFERENCES updates(id) ON DELETE CASCADE,
  sha256 TEXT NOT NULL,
  PRIMARY KEY (update_id, sha256)
);
